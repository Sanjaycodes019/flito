const pad = (n) => String(n).padStart(2, '0');

export const daysInBsMonth = (year, month) => MONTH_DAYS[year]?.[month - 1] ?? null;

const parseDayKey = (dayKey) => {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(dayKey || '');
  return match ? Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3])) : null;
};

const keyOfMs = (ms) => new Date(ms).toISOString().slice(0, 10);

// The BS day for an AD day key, or null outside the supported years.
export const adToBs = (dayKey) => {
  const ms = parseDayKey(dayKey);
  if (ms === null) return null;
  let left = Math.round((ms - EPOCH_MS) / DAY_MS);
  if (left < 0) return null;

  for (let year = BS_MIN_YEAR; year <= BS_MAX_YEAR; year += 1) {
    for (let month = 1; month <= 12; month += 1) {
      const length = MONTH_DAYS[year][month - 1];
      if (left < length) return { year, month, day: left + 1 };
      left -= length;
    }
  }
  return null;
};

// The AD day key for a BS day, or null when it isn't a real BS day.
export const bsToAd = (year, month, day) => {
  const length = daysInBsMonth(year, month);
  if (!length || !Number.isInteger(day) || day < 1 || day > length) return null;

  let days = 0;
  for (let y = BS_MIN_YEAR; y < year; y += 1) days += MONTH_DAYS[y].reduce((sum, n) => sum + n, 0);
  for (let m = 1; m < month; m += 1) days += MONTH_DAYS[year][m - 1];
  return keyOfMs(EPOCH_MS + (days + day - 1) * DAY_MS);
};

const DEVANAGARI_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
export const localizeDigits = (value, language) => (
  language === 'ne' ? String(value).replace(/\d/g, (d) => DEVANAGARI_DIGITS[d]) : String(value)
);

export const bsKey = ({ year, month, day }) => `${year}-${pad(month)}-${pad(day)}`;
